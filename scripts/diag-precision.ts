import { readFile } from "node:fs/promises";
import { MemoryFile } from "../packages/core/src/index.ts";
import { collectLeaves, replacePrecision } from "../eval/memory/metrics.ts";
import { loadRecord } from "../eval/halumem/adapter.ts";
import { homedir } from "node:os";
import { join } from "node:path";

const CACHE = join(homedir(), ".cache", "memory-x", "halumem", "HaluMem-Medium.jsonl");
const rec = JSON.parse((await readFile(CACHE, "utf8")).split("\n").filter(l => l.trim())[0]!);
const RUNS = "eval/halumem/runs";
const leavesA = collectLeaves((await MemoryFile.open(`${RUNS}/2026-11-21T02-19-03-051Z-pi/rec-1`)).root as any);
const leavesB = collectLeaves((await MemoryFile.open(`${RUNS}/2026-11-21T02-19-05-022Z-pi/rec-1-off4`)).root as any);
const merged = [...leavesA, ...leavesB];
const partA = loadRecord(rec, { sessions: 4 });
const partB = loadRecord(rec, { sessions: 4, offset: 4 });
const full = loadRecord(rec, { sessions: 8 });
console.log("== precision：分片口径 vs 合并树（串行等价）==");
console.log(`A 7对  仅A树 ${replacePrecision(leavesA, partA.expectReplace).precision.toFixed(3)} | 合并树 ${replacePrecision(merged, partA.expectReplace).precision.toFixed(3)}`);
console.log(`B 17对 仅B树 ${replacePrecision(leavesB, partB.expectReplace).precision.toFixed(3)} | 合并树 ${replacePrecision(merged, partB.expectReplace).precision.toFixed(3)}`);
const r = replacePrecision(merged, full.expectReplace);
console.log(`全24对 合并树 ${r.precision.toFixed(3)}（stale ${r.stale.length}）`);
